import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import prettier from 'prettier';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const appDir = path.resolve(__dirname, '../apps/web/.next/server/app');
const committedFile = path.resolve(__dirname, '../packages/security/src/static-hashes.ts');

const THEME_SCRIPT_HASH = "'sha256-uzc/ICGCVhC9uE7iS0jwoALziW9F9jnNPGlor+yZDuk='";

if (!fs.existsSync(appDir)) {
  console.error('Error: Build artifacts directory does not exist:', appDir);
  console.error('Run "pnpm build" before verifying static script hashes.');
  process.exit(1);
}

if (!fs.existsSync(committedFile)) {
  console.error('Error: Committed static-hashes file does not exist:', committedFile);
  process.exit(1);
}

function getAllHtmlFiles(dir) {
  let results = [];
  const list = fs.readdirSync(dir).sort();
  for (const file of list) {
    const fullPath = path.join(dir, file);
    const stat = fs.statSync(fullPath);
    if (stat && stat.isDirectory()) {
      results = results.concat(getAllHtmlFiles(fullPath));
    } else if (file.endsWith('.html')) {
      results.push(fullPath);
    }
  }
  return results.sort();
}

const files = getAllHtmlFiles(appDir);
const hashes = new Set([THEME_SCRIPT_HASH]);

for (const filePath of files) {
  const html = fs.readFileSync(filePath, 'utf8');
  const scriptRegex = /<script\b[^>]*>([\s\S]*?)<\/script>/gi;
  let match;
  while ((match = scriptRegex.exec(html)) !== null) {
    const content = match[1];
    if (content && content.trim()) {
      const hash = "'sha256-" + crypto.createHash('sha256').update(content).digest('base64') + "'";
      hashes.add(hash);
    }
  }
}

const sortedHashes = Array.from(hashes).sort();
const expectedContent = `/**
 * Automatically extracted inline script hashes for static prerendered routes.
 * Generated by scripts/extract-static-hashes.mjs after next build.
 */
export const STATIC_THEME_SCRIPT_HASH = "${THEME_SCRIPT_HASH.replace(/'/g, "\\'")}";

export const STATIC_ROUTE_SCRIPT_HASHES: string[] = ${JSON.stringify(sortedHashes, null, 2)};
`;

const prettierConfig = (await prettier.resolveConfig(committedFile)) || {};
const formattedExpected = await prettier.format(expectedContent, {
  ...prettierConfig,
  filepath: committedFile,
});

const currentContent = fs.readFileSync(committedFile, 'utf8');

if (currentContent !== formattedExpected) {
  console.error(
    'FAIL: Committed static script hashes in packages/security/src/static-hashes.ts are STALE.',
  );
  console.error(`Expected ${sortedHashes.length} hashes, but committed file differs.`);
  console.error(
    'Run "pnpm build" to regenerate static hashes, review the diff, and commit the updated file.',
  );
  process.exit(1);
}

console.log(
  `PASS: Static hashes are deterministic and current (${sortedHashes.length} hashes verified).`,
);
process.exit(0);
